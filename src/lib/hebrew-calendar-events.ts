/**
 * 하누카는 키슬레브 25일부터 여드레인데, 그 해 키슬레브가 29일이냐 30일이냐에
 * 따라 끝이 테벳 2일이 되기도 3일이 되기도 한다. 그래서 표를 두지 않고
 * 그 날부터 최대 이레를 거슬러 올라가며 키슬레브 25일을 찾는다.
 */
function hanukkahDay(
  monthKey: string,
  day: number,
  lookBack: (daysAgo: number) => { monthKey: string; day: number },
): number | null {
  // 여드레가 걸칠 수 있는 범위 밖이면 거슬러 세지 않는다 — 달력 한 면에서
  // 이 함수가 42번 불리므로 헛된 Intl 호출을 미리 잘라 낸다.
  if (monthKey === 'Kislev' ? day < 25 : monthKey === 'Tevet' ? day > 3 : true) return null;
  for (let back = 0; back < 8; back++) {
    const past = back === 0 ? { monthKey, day } : lookBack(back);
    if (past.monthKey === 'Kislev' && past.day === 25) return back + 1;
  }
  return null;
}

export function getHebrewDayEvents(
  monthKey: string,
  day: number,
  lookBack: (daysAgo: number) => { monthKey: string; day: number },
): HebrewDayInfo {
  const key = `${monthKey}-${day}`;
  const festivals: string[] = [];

  const fixed = FIXED_FESTIVALS[key];
  if (fixed) festivals.push(fixed);

  const hanukkah = hanukkahDay(monthKey, day, lookBack);
  if (hanukkah != null) festivals.push(`수전절(하누카) ${hanukkah}일째`);

  return {
    festivals,
    bible: BIBLE[key] ?? [],
    history: HISTORY[key] ?? [],
    monthNote: HEBREW_MONTH_NOTE[monthKey],
  };
}

/** 달력 칸에 점을 찍을지 — 절기나 사건이 하나라도 있는 날인가. */
export function hebrewDayHasContent(monthKey: string, day: number): boolean {
  const key = `${monthKey}-${day}`;
  return key in FIXED_FESTIVALS || key in BIBLE || key in HISTORY;
}

const DAY_MS = 24 * 60 * 60 * 1000;

/** 그레고리력 날짜 하나를 넣으면 그 날의 히브리력 절기·사건을 돌려준다. */
export function getHebrewDayInfoForDate(date: Date): HebrewDayInfo {
  const { monthKey, day } = getHebrewFields(date);
  return getHebrewDayEvents(monthKey, day, (daysAgo) =>
    getHebrewFields(new Date(date.getTime() - daysAgo * DAY_MS)),
  );
}

/** 달력 칸용 — 하누카까지 포함해 이 날에 보여 줄 것이 있는지. */
export function hebrewDateHasContent(date: Date): boolean {
  const { monthKey, day } = getHebrewFields(date);
  if (hebrewDayHasContent(monthKey, day)) return true;
  return (
    hanukkahDay(monthKey, day, (daysAgo) =>
      getHebrewFields(new Date(date.getTime() - daysAgo * DAY_MS)),
    ) != null
  );
}
