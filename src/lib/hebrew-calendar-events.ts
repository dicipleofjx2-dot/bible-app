// 히브리력 날짜(월·일)에 붙는 절기 / 성경 사건 / 역사 사건.
//
// 키는 `${monthKey}-${day}` 이고 monthKey 는 `hebrew-date.ts` 의
// `getHebrewFields()` 가 돌려주는 정규화된 영문 월 이름이다. 윤년의
// 'Adar II' 는 평년 'Adar' 로 합쳐서 들어온다 — 부림절과 아달월 사건은
// 유대력에서 윤년에 둘째 아달에 지키기 때문이다. 윤달인 'Adar I' 만
// 따로 'AdarI' 키를 쓴다.
//
// 원칙 세 가지:
//  1. 성경 사건은 **본문이 날짜를 직접 말하는 것**만 `ref` 를 붙여 넣는다.
//  2. 본문에 날짜가 없고 유대 전통이나 교회 전통으로만 그 날에 두는 것은
//     본문에 "전통" 이라고 밝힌다. 근거 없이 단정하지 않는다.
//  3. 성경 본문끼리 날짜가 어긋나는 곳(아브 7일/10일, 아달 25일/27일)은
//     감추지 말고 양쪽을 다 적는다.

import { getHebrewFields } from '@/lib/hebrew-date';

export type HebrewDayEntry = {
  title: string;
  body: string;
  /** 날짜를 직접 말하는 성경 구절. 전통에만 근거한 항목은 비운다. */
  ref?: string;
};

export type HebrewDayInfo = {
  /** 그 날의 유대 절기 이름 (하누카처럼 여러 날짜에 걸친 것 포함). */
  festivals: string[];
  bible: HebrewDayEntry[];
  history: HebrewDayEntry[];
  /** 그 달 자체에 대한 한 문단. 사건이 없는 날에도 보여 준다. */
  monthNote?: string;
};

